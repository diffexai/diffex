	/** Show a custom component with keyboard focus. Overlay mode renders on top of existing content. */
	private async showExtensionCustom<T>(
		factory: (
			tui: TUI,
			theme: Theme,
			keybindings: KeybindingsManager,
			done: (result: T) => void,
		) => (Component & { dispose?(): void }) | Promise<Component & { dispose?(): void }>,
		options?: {
			overlay?: boolean;
			overlayOptions?: OverlayOptions | (() => OverlayOptions);
			onHandle?: (handle: OverlayHandle) => void;
		},
	): Promise<T> {
		const isOverlay = options?.overlay ?? false;

		return new Promise((resolve, reject) => {
			let component: Component & { dispose?(): void };
			let editorToken: object | undefined;
			let overlayHandle: OverlayHandle | undefined;
			let closed = false;
			const dispose = () => {
				try {
					component?.dispose?.();
				} catch {
					/* ignore dispose errors */
				}
			};

			const close = (result: T) => {
				if (closed) return;
				closed = true;
				if (isOverlay) overlayHandle?.hide();
				else if (editorToken) this.closeEditorUi(editorToken);
				resolve(result);
				dispose();
			};

			Promise.resolve(factory(this.ui, theme, this.keybindings, close))
				.then((c) => {
					if (closed) {
						c.dispose?.();
						return;
					}
					component = c;
					if (isOverlay) {
						// Resolve overlay options - can be static or dynamic function
						const resolveOptions = (): OverlayOptions | undefined => {
							if (options?.overlayOptions) {
								const opts =
									typeof options.overlayOptions === "function"
										? options.overlayOptions()
										: options.overlayOptions;
								return opts;
							}
							// Fallback: use component's width property if available
							const w = (component as { width?: number }).width;
							return w ? { width: w } : undefined;
						};
						overlayHandle = this.ui.showOverlay(component, resolveOptions());
						// Expose handle to caller for visibility control
						options?.onHandle?.(overlayHandle);
					} else {
						editorToken = this.mountEditorUi(component, component, () => {
							if (closed) return;
							closed = true;
							dispose();
							reject(new Error("Interactive UI was replaced"));
						});
					}
				})
				.catch((err) => {
					if (closed) return;
					closed = true;
					if (overlayHandle) overlayHandle.hide();
					else if (editorToken) this.closeEditorUi(editorToken);
					dispose();
					reject(err);
				});
		});
	}

